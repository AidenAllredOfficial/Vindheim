export interface ActionResult {
  /** Layer weight 0..1. */
  w: number;
  aim: number;
  fullBody: boolean;
  /** Tremble amount 0..1 (channels, charges). */
  shake: number;
  /** Seconds the entry blend may take. */
  blendIn: number;
}
const RES: ActionResult = { w: 0, aim: 0, fullBody: false, shake: 0, blendIn: 0.08 };

export function keyedFor(kind: AnimKind, cls: WeaponClass): Keyed | undefined {
  if (kind === 'channel') return cls === 'none' ? CHANNEL_OPEN : CHANNEL_ARMED;
  return KEYED[kind];
}

/**
 * Evaluate a keyed action at time t (seconds since the action began). The strike lands exactly at
 * def.windup. Returns null for kinds that are not keyed (movement signatures driven by `mv`).
 */
export function evalAction(kind: AnimKind, cls: WeaponClass, def: AbilityDef, t: number, out: Pose): ActionResult | null {
  const k = keyedFor(kind, cls);
  if (!k) return null;
  const W = def.windup, A = def.active, R = def.recovery, T = W + A + R;
  // heavier (slower) abilities take a little longer through the strike itself
  const s = clamp(k.snap * (1 + 0.5 * clamp((W - 0.22) / 0.25, 0, 1)), 0.03, Math.max(0.03, W * 0.62));
  const tA = Math.max(0, W - s);
  const f = k.follow;
  // quick abilities get a compact wind-up: there is no time to read (or perform) a big one
  const compact = k.pre ? 0 : clamp(1 - W / 0.24, 0, 0.45);
  const pw = lerp(k.pow, 1.35, compact * 2);
  let shake = 0;
  if (t < tA) {
    const u = t / tA;
    if (k.pre) { out.mix(k.pre, k.ant, easeInOut(u)); shake = k.tremble * u * u; }
    else out.mix(k.ant, k.hit, compact - k.creep * (1 - compact) * easeOut(u, 2));
  } else if (t < W) {
    const u = (t - tA) / Math.max(1e-4, W - tA);
    out.mix(k.ant, k.hit, lerp(k.pre ? 0 : compact - k.creep * (1 - compact), 1, easeIn(u, pw)));
    shake = k.tremble * (1 - u);
  } else if (k.sustain && t < W + A) {
    out.copy(k.hit);
    shake = 0.55;
  } else {
    const t0 = k.sustain ? W + A : W;
    const u = (t - t0) / f;
    if (u < 1) out.mix(k.hit, k.fol, easeOut(u, 2)); else out.copy(k.fol);
    if (!k.sustain && t < W + A) shake = k.tremble * 0.6;
  }
  // hold the follow-through, then hand back to locomotion over the tail of the recovery
  const hold = (k.sustain ? W + A : W) + Math.max(f, k.sustain ? 0 : A) ;
  const fadeStart = Math.min(T - 0.05, hold + (T - hold) * 0.3);
  const fu = t <= fadeStart ? 0 : (t - fadeStart) / Math.max(0.05, T - fadeStart);
  RES.w = 1 - easeInOut(fu);
  if (k.rec && fu > 0) { _a.copy(out); out.mix(_a, k.rec, easeInOut(Math.min(1, fu * 1.7))); }
  RES.aim = k.aim; RES.fullBody = k.fullBody; RES.shake = shake;
  RES.blendIn = clamp(tA * 0.75, 0.045, 0.11);
  void _a;
  return RES;
}

