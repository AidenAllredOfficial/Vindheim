  snap: number;
  /** Seconds from the strike to the end of the follow-through. */
  follow: number;
  /** How far the wind-up keeps creeping away from the strike (fraction of ant -> hit). */
  creep: number;
  /** Strike easing exponent (> 1 accelerates into the hit). */
  pow: number;
  /** Arms follow the aim pitch. */
  aim: number;
  /** Action owns the legs even while running (kicks). */
